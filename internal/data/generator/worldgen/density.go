// densityNode describes one shared expression in the generated standard graph.
type densityNode struct {
	raw      json.RawMessage
	kind     string
	fields   map[string]json.RawMessage
	children map[string]int
}

// densityEmitter preserves expression order while sharing named immutable graph nodes.
type densityEmitter struct {
	definitions map[string]json.RawMessage
	nodes       []*densityNode
	indices     map[string]int
	roots       map[string]int
	order       []int
	splines     []generatedSpline
	splineIDs   map[string]int
}

// canonical normalizes JSON keys and numbers for development-time graph identities.
func canonical(raw json.RawMessage) string {
	var value any
	must(json.Unmarshal(raw, &value))
	data, err := json.Marshal(value)
	must(err)
	return string(data)
}

// generateDensity emits direct Go evaluators and seed-dependent bindings from the bundled router.
func generateDensity(directory, output string, routerRaw json.RawMessage) {
	e := &densityEmitter{definitions: make(map[string]json.RawMessage), indices: make(map[string]int), roots: make(map[string]int), splineIDs: make(map[string]int)}
	must(filepath.WalkDir(filepath.Join(directory, "density_function"), func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".json") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		relative, err := filepath.Rel(filepath.Join(directory, "density_function"), path)
		if err != nil {
			return err
		}
		id := "minecraft:" + strings.TrimSuffix(filepath.ToSlash(relative), ".json")
		e.definitions[id] = data
		return nil
	}))
	router := fields(routerRaw)
	finalIndex := e.node(router["final_density"])
	finalChannels := make([]int, 0, 5)
	for index, node := range e.nodes {
		if node.kind == "interpolated" {
			finalChannels = append(finalChannels, index)
		}
	}
	keys := make([]string, 0, len(router))
	for key := range router {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		index := e.node(router[key])
		e.roots[canonical(router[key])] = index
	}
	for id, raw := range e.definitions {
		if index, ok := e.indices[canonical(raw)]; ok {
			encoded, _ := json.Marshal(id)
			e.roots[canonical(encoded)] = index
		}
	}
	var source, bindings, functions bytes.Buffer
	source.WriteString("// Code generated by internal/data/generator/worldgen; DO NOT EDIT.\npackage density\nimport(\"encoding/json\";\"math\";\"github.com/vitismc/vitis/internal/world/worldgen/noise\")\n")
	fmt.Fprintf(&source, "// standardDensity owns immutable direct evaluators for the validated Overworld router.\ntype standardDensity struct { functions [%d]Function; noises [%d]*noise.Normal; markers [%d]*Marker; interpolated [%d]*interpolated; blended [%d]*blendedFunction; splines [%d]spline; lower,upper [%d]float64; roots map[string]Function; noiseIDs [%d]int; oreToggleID int }\n", len(e.nodes), len(e.nodes), len(e.nodes), len(e.nodes), len(e.nodes), len(e.nodes), len(e.nodes), len(e.nodes))
	bindings.WriteString("// newStandardDensity binds seed-specific inputs without changing arithmetic order.\nfunc newStandardDensity(c *Compiler)(*standardDensity,error){\ng:=&standardDensity{roots:make(map[string]Function)}\n")
	for index := range e.nodes {
		fmt.Fprintf(&bindings, "g.functions[%d]=functionFunc(g.n%d)\n", index, index)
	}
	for _, index := range e.order {
		e.emitNode(index, &bindings, &functions)
	}
	e.emitSplines(&functions)
	for index, node := range e.nodes {
		if node.kind == "interpolated" {
			fmt.Fprintf(&bindings, "c.interpolators=append(c.interpolators,g.interpolated[%d])\n", index)
		}
	}
	fmt.Fprintf(&bindings, "g.functions[%d]=&overworldFillDensity{generic:g.functions[%d],ids:[5]int{", finalIndex, finalIndex)
	if len(finalChannels) != 5 {
		panic("unexpected standard final interpolation graph")
	}
	for _, index := range finalChannels {
		fmt.Fprintf(&bindings, "g.interpolated[%d].id,", index)
	}
	bindings.WriteString("}}\n")
	rootKeys := make([]string, 0, len(e.roots))
	for key := range e.roots {
		rootKeys = append(rootKeys, key)
	}
	sort.Strings(rootKeys)
	for _, key := range rootKeys {
		fmt.Fprintf(&bindings, "g.roots[%q]=g.functions[%d]\n", key, e.roots[key])
	}
	// The validated router exposes its ore toggle directly through interpolation.
	toggleIndex := e.roots[canonical(router["vein_toggle"])]
	if e.nodes[toggleIndex].kind != "interpolated" {
		panic("standard ore toggle must be interpolated")
	}
	fmt.Fprintf(&bindings, "g.oreToggleID=g.interpolated[%d].id\nreturn g,nil\n}\n", toggleIndex)
	source.Write(bindings.Bytes())
	source.Write(functions.Bytes())
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		os.WriteFile("/tmp/vitis-generated-density-invalid.go", source.Bytes(), 0600)
	}
	must(err)
	must(os.WriteFile(output, formatted, 0644))
}

// node resolves shared references and records children in semantic evaluation order.
func (e *densityEmitter) node(raw json.RawMessage) int {
	key := canonical(raw)
	if len(key) > 0 && key[0] == '"' {
		id := stringValue(raw)
		value, ok := e.definitions[id]
		if !ok {
			panic("unknown density " + id)
		}
		return e.node(value)
	}
	if index, ok := e.indices[key]; ok {
		return index
	}
	index := len(e.nodes)
	n := &densityNode{raw: json.RawMessage(key), children: make(map[string]int)}
	e.indices[key] = index
	e.nodes = append(e.nodes, n)
	if key[0] != '{' {
		n.kind = "constant"
		e.order = append(e.order, index)
		return index
	}
	n.fields = fields(raw)
	n.kind = strings.TrimPrefix(stringValue(n.fields["type"]), "minecraft:")
	var children []string
	switch n.kind {
	case "add", "mul", "min", "max":
		children = []string{"argument1", "argument2"}
	case "abs", "square", "cube", "half_negative", "quarter_negative", "squeeze", "blend_density", "interpolated", "flat_cache", "cache_2d", "cache_once", "cache_all_in_cell":
		children = []string{"argument"}
	case "clamp", "weird_scaled_sampler":
		children = []string{"input"}
	case "range_choice":
		children = []string{"input", "when_in_range", "when_out_of_range"}
	case "shifted_noise":
		children = []string{"shift_x", "shift_y", "shift_z"}
	}
	for _, field := range children {
		n.children[field] = e.node(n.fields[field])
	}
	if n.kind == "spline" {
		n.children["spline"] = e.splineNode(n.fields["spline"])
	}
	e.order = append(e.order, index)
	return index
}

// number returns an explicit runtime float literal, avoiding constant folding across operations.
func number(raw json.RawMessage) string {
	var value float64
	must(json.Unmarshal(raw, &value))
	return "float64(" + strconv.FormatFloat(value, 'g', -1, 64) + ")"
}

// emitNode emits one direct evaluator and initializes its exact conservative bounds.
func (e *densityEmitter) emitNode(index int, bind, functions *bytes.Buffer) {
	n := e.nodes[index]
	f := n.fields
	body := ""
	lower, upper := "math.Inf(-1)", "math.Inf(1)"
	child := func(field string) string { return fmt.Sprintf("g.n%d(p)", n.children[field]) }
	lo := func(field string) string { return fmt.Sprintf("g.lower[%d]", n.children[field]) }
	hi := func(field string) string { return fmt.Sprintf("g.upper[%d]", n.children[field]) }
	switch n.kind {
	case "constant":
		body = "return " + number(n.raw)
		lower, upper = number(n.raw), number(n.raw)
	case "blend_alpha":
		body = "return 1"
		lower, upper = "1", "1"
	case "blend_offset":
		body = "return 0"
		lower, upper = "0", "0"
	case "add":
		body = "return " + child("argument1") + " + " + child("argument2")
		lower, upper = lo("argument1")+"+"+lo("argument2"), hi("argument1")+"+"+hi("argument2")
	case "mul":
		body = "return " + child("argument1") + " * " + child("argument2")
		fmt.Fprintf(bind, "{ products:=[4]float64{%s*%s,%s*%s,%s*%s,%s*%s}; low,high:=products[0],products[0];for _,v:=range products[1:]{low=math.Min(low,v);high=math.Max(high,v)};g.lower[%d],g.upper[%d]=low,high }\n", lo("argument1"), lo("argument2"), lo("argument1"), hi("argument2"), hi("argument1"), lo("argument2"), hi("argument1"), hi("argument2"), index, index)
		lower, upper = fmt.Sprintf("g.lower[%d]", index), fmt.Sprintf("g.upper[%d]", index)
	case "min":
		body = fmt.Sprintf("value:=%s;if value<%s{return value};return math.Min(value,%s)", child("argument1"), lo("argument2"), child("argument2"))
		lower, upper = "math.Min("+lo("argument1")+","+lo("argument2")+")", "math.Min("+hi("argument1")+","+hi("argument2")+")"
	case "max":
		body = fmt.Sprintf("value:=%s;if value>%s{return value};return math.Max(value,%s)", child("argument1"), hi("argument2"), child("argument2"))
		lower, upper = "math.Max("+lo("argument1")+","+lo("argument2")+")", "math.Max("+hi("argument1")+","+hi("argument2")+")"
	case "abs":
		body = "return math.Abs(" + child("argument") + ")"
		lower = "0"
		upper = "math.Max(math.Abs(" + lo("argument") + "),math.Abs(" + hi("argument") + "))"
	case "square":
		body = "value:=" + child("argument") + ";return value*value"
		lower = "0"
		upper = "math.Max(" + lo("argument") + "*" + lo("argument") + "," + hi("argument") + "*" + hi("argument") + ")"
	case "cube":
		body = "value:=" + child("argument") + ";return value*value*value"
		lower, upper = lo("argument")+"*"+lo("argument")+"*"+lo("argument"), hi("argument")+"*"+hi("argument")+"*"+hi("argument")
	case "half_negative", "quarter_negative":
		factor := "0.5"
		if n.kind == "quarter_negative" {
			factor = "0.25"
		}
		body = "value:=" + child("argument") + ";if value<0 {value*=" + factor + "};return value"
		lower, upper = lo("argument"), hi("argument")
	case "squeeze":
		body = "value:=math.Max(-1,math.Min(1," + child("argument") + "));return value/2-value*value*value/24"
	case "blend_density":
		body = "return " + child("argument")
		lower, upper = lo("argument"), hi("argument")
	case "clamp":
		body = "return math.Max(" + number(f["min"]) + ",math.Min(" + number(f["max"]) + "," + child("input") + "))"
		lower, upper = number(f["min"]), number(f["max"])
	case "range_choice":
		body = fmt.Sprintf("value:=%s;if value>=%s && value<%s{return %s};return %s", child("input"), number(f["min_inclusive"]), number(f["max_exclusive"]), child("when_in_range"), child("when_out_of_range"))
		lower, upper = "math.Min("+lo("when_in_range")+","+lo("when_out_of_range")+")", "math.Max("+hi("when_in_range")+","+hi("when_out_of_range")+")"
	case "y_clamped_gradient":
		body = fmt.Sprintf("delta:=(float64(p.Y)-%s)/(%s-%s);if delta<0{delta=0}else if delta>1{delta=1};return %s+delta*(%s-%s)", number(f["from_y"]), number(f["to_y"]), number(f["from_y"]), number(f["from_value"]), number(f["to_value"]), number(f["from_value"]))
		lower, upper = "math.Min("+number(f["from_value"])+","+number(f["to_value"])+")", "math.Max("+number(f["from_value"])+","+number(f["to_value"])+")"
	case "noise", "shift_a", "shift_b", "shifted_noise", "weird_scaled_sampler":
		field := "noise"
		if n.kind == "shift_a" || n.kind == "shift_b" {
			field = "argument"
		}
		fmt.Fprintf(bind, "{sampler,err:=c.resolveNoise(%q);if err!=nil{return nil,err};g.noises[%d]=sampler}\n", stringValue(f[field]), index)
		noiseExpr := fmt.Sprintf("g.noises[%d]", index)
		lower, upper = "-"+noiseExpr+".MaxValue()", noiseExpr+".MaxValue()"
		switch n.kind {
		case "noise":
			if number(f["y_scale"]) == "float64(0)" {
				fmt.Fprintf(bind, "g.markers[%d]=&Marker{ID:c.nextCacheID,Kind:\"cache_2d\",Function:functionFunc(func(p Position)float64{return %s.SampleXZ(float64(p.X)*%s,float64(p.Z)*%s)})};c.nextCacheID++\n", index, noiseExpr, number(f["xz_scale"]), number(f["xz_scale"]))
				body = fmt.Sprintf("return g.markers[%d].Sample(p)", index)
			} else {
				fmt.Fprintf(bind, "g.noiseIDs[%d]=c.nextCacheID;c.nextCacheID++\n", index)
				body = fmt.Sprintf("return sampleStandardNoise(g.noiseIDs[%d],p,%s,%s,%s)", index, noiseExpr, number(f["xz_scale"]), number(f["y_scale"]))
			}
		case "shift_a":
			body = "return " + noiseExpr + ".SampleXZ(float64(p.X)*0.25,float64(p.Z)*0.25)*4"
			lower += "*4"
			upper += "*4"
		case "shift_b":
			body = "return " + noiseExpr + ".Sample(float64(p.Z)*0.25,float64(p.X)*0.25,0)*4"
			lower += "*4"
			upper += "*4"
		case "shifted_noise":
			body = fmt.Sprintf("return %s.Sample(float64(p.X)*%s+%s,float64(p.Y)*%s+%s,float64(p.Z)*%s+%s)", noiseExpr, number(f["xz_scale"]), child("shift_x"), number(f["y_scale"]), child("shift_y"), number(f["xz_scale"]), child("shift_z"))
			if number(f["y_scale"]) == "float64(0)" && e.nodes[n.children["shift_y"]].kind == "constant" && number(e.nodes[n.children["shift_y"]].raw) == "float64(0)" {
				body = fmt.Sprintf("return %s.SampleXZ(float64(p.X)*%s+%s,float64(p.Z)*%s+%s)", noiseExpr, number(f["xz_scale"]), child("shift_x"), number(f["xz_scale"]), child("shift_z"))
			}
		case "weird_scaled_sampler":
			body = fmt.Sprintf("rarity:=spaghettiRarity(%s,%q);return rarity*math.Abs(%s.Sample(float64(p.X)/rarity,float64(p.Y)/rarity,float64(p.Z)/rarity))", child("input"), stringValue(f["rarity_value_mapper"]), noiseExpr)
			lower, upper = "0", "math.Inf(1)"
		}
	case "old_blended_noise":
		fmt.Fprintf(bind, "{function,err:=c.compileBlended(json.RawMessage(%q));if err!=nil{return nil,err};unwrapped,_,_:=unwrapBounds(function);g.blended[%d]=unwrapped.(*blendedFunction)}\n", string(n.raw), index)
		body = fmt.Sprintf("return g.blended[%d].Sample(p)", index)
		lower, upper = fmt.Sprintf("-g.blended[%d].sampler.MaxValue()", index), fmt.Sprintf("g.blended[%d].sampler.MaxValue()", index)
	case "spline":
		body = fmt.Sprintf("return float64(g.s%d(p))", n.children["spline"])
	case "flat_cache", "cache_2d", "cache_once", "cache_all_in_cell":
		fmt.Fprintf(bind, "g.markers[%d]=&Marker{ID:c.nextCacheID,Kind:%q,Function:g.functions[%d]};c.nextCacheID++\n", index, n.kind, n.children["argument"])
		body = fmt.Sprintf("return g.markers[%d].Sample(p)", index)
		if n.kind == "cache_once" {
			body = fmt.Sprintf("if p.Evaluation==nil{return %s};id:=g.markers[%d].ID;if value,ok:=p.Evaluation.lastStandardValue(id,p);ok{return value};value:=%s;p.Evaluation.storeStandardLast(id,p,value);return value", child("argument"), index, child("argument"))
		} else if n.kind == "cache_2d" || n.kind == "flat_cache" {
			prefix := "p.Y=0;"
			if n.kind == "flat_cache" {
				prefix += "p.X=floorToMultiple(p.X,4);p.Z=floorToMultiple(p.Z,4);"
			}
			body = prefix + fmt.Sprintf("if p.Evaluation==nil{return %s};id:=g.markers[%d].ID;if value,ok:=p.Evaluation.standardHorizontalValue(id,p);ok{return value};value:=%s;p.Evaluation.storeStandardHorizontal(id,p,value);return value", child("argument"), index, child("argument"))
		}
		lower, upper = lo("argument"), hi("argument")
	case "interpolated":
		fmt.Fprintf(bind, "{width,height:=c.registry.CellWidth,c.registry.CellHeight;g.interpolated[%d]=&interpolated{id:c.nextCacheID,function:g.functions[%d],width:width,height:height,widthMask:width-1,heightMask:height-1,widthInverse:1/float64(width),heightInverse:1/float64(height),powerOfTwo:width&(width-1)==0&&height&(height-1)==0};c.nextCacheID++}\n", index, n.children["argument"])
		body = fmt.Sprintf("return g.interpolated[%d].Sample(p)", index)
		lower, upper = lo("argument"), hi("argument")
	default:
		panic("unsupported standard density " + n.kind)
	}
	// Assign bounds before scaling negative values, with marker channels published in graph order later.
	if n.kind == "half_negative" || n.kind == "quarter_negative" {
		factor := "0.5"
		if n.kind == "quarter_negative" {
			factor = "0.25"
		}
		fmt.Fprintf(bind, "g.lower[%d],g.upper[%d]=%s,%s;if g.lower[%d]<0{g.lower[%d]*=%s};if g.upper[%d]<0{g.upper[%d]*=%s}\n", index, index, lower, upper, index, index, factor, index, index, factor)
	} else if lower != fmt.Sprintf("g.lower[%d]", index) || upper != fmt.Sprintf("g.upper[%d]", index) {
		fmt.Fprintf(bind, "g.lower[%d],g.upper[%d]=%s,%s\n", index, index, lower, upper)
	}
	fmt.Fprintf(functions, "// n%d evaluates one immutable standard expression.\nfunc(g *standardDensity)n%d(p Position)float64{%s}\n", index, index, body)
}
