// Command worldgen generates specialized evaluators from bundled world generation resources.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	generatedbiome "github.com/vitismc/vitis/internal/data/generated/biome"
)

// surfaceEmitter flattens immutable rule branches and binds uncommon conditions once.
type surfaceEmitter struct {
	body       bytes.Buffer
	conditions []json.RawMessage
	states     []json.RawMessage
	gradients  []string
	deep       bool
}

// main generates checked-in Go without affecting runtime resource loading.
func main() {
	version := flag.String("version", "1.21.4", "Minecraft version used to select the default resource directory")
	resources := flag.String("resources", "", "Resource directory (default: .mcdata/<version>/vanilla/data/minecraft/worldgen)")
	output := flag.String("surface-output", "internal/world/worldgen/surface_standard_generated.go", "Surface output")
	netherOutput := flag.String("nether-surface-output", "internal/world/worldgen/surface_nether_generated.go", "Nether surface output")
	densityOutput := flag.String("density-output", "internal/world/worldgen/density/standard_generated.go", "Density output")
	flag.Parse()
	if *resources == "" {
		*resources = filepath.Join(".mcdata", *version, "vanilla", "data", "minecraft", "worldgen")
	}
	data, err := os.ReadFile(filepath.Join(*resources, "noise_settings", "overworld.json"))
	must(err)
	var settings map[string]json.RawMessage
	must(json.Unmarshal(data, &settings))
	generateSurface(settings["surface_rule"], *output, "")
	generateDensity(*resources, *densityOutput, settings["noise_router"])
	data, err = os.ReadFile(filepath.Join(*resources, "noise_settings", "nether.json"))
	must(err)
	must(json.Unmarshal(data, &settings))
	generateSurface(settings["surface_rule"], *netherOutput, "Nether")
}

// generateSurface emits ordered surface branches with a dimension-specific binding name.
func generateSurface(rule json.RawMessage, output, dimension string) {
	e := &surfaceEmitter{}
	fullReturns := e.rule(rule)
	fullSurface := append([]byte(nil), e.body.Bytes()...)
	deepReturns := false
	if dimension == "" {
		e.body.Reset()
		e.deep = true
		deepReturns = e.rule(rule)
	}
	var source bytes.Buffer
	source.WriteString("// Code generated by internal/data/generator/worldgen; DO NOT EDIT.\npackage worldgen\nimport (\"encoding/json\"; \"github.com/vitismc/vitis/internal/block\"; \"github.com/vitismc/vitis/internal/world/worldgen/noise\"; worldrandom \"github.com/vitismc/vitis/internal/world/worldgen/random\")\n")
	fmt.Fprintf(&source, "// bindStandard%sSurface resolves immutable generated rule inputs.\nfunc (s *surfaceSystem) bindStandard%sSurface(resolve func(string)(*noise.Normal,error)) error {\n", dimension, dimension)
	for _, condition := range e.conditions {
		fmt.Fprintf(&source, "{ condition,err := s.compileCondition(json.RawMessage(%q),nil,resolve); if err!=nil{return err}; s.standardConditions=append(s.standardConditions,condition) }\n", string(condition))
	}
	for _, name := range e.gradients {
		fmt.Fprintf(&source, "s.standardGradients=append(s.standardGradients,s.random.FromHashOf(normalizeResourceID(%q)).ForkPositional())\n", name)
	}
	for _, state := range e.states {
		fmt.Fprintf(&source, "{ var value BlockState; if err:=json.Unmarshal(json.RawMessage(%q),&value);err!=nil{return err};state,err:=block.BlockStateFromProperties(value.Name,value.Properties);if err!=nil{return err};s.standardStates=append(s.standardStates,state.ID()) }\n", string(state))
	}
	fmt.Fprintf(&source, "return nil\n}\n// applyStandard%sSurface evaluates ordered rules without interface dispatch.\nfunc applyStandard%sSurface(c *surfaceContext)(int32,bool) {\n", dimension, dimension)
	source.Write(fullSurface)
	if !fullReturns {
		source.WriteString("return 0,false\n")
	}
	source.WriteString("}\n")
	if dimension == "" {
		fmt.Fprintf(&source, "// applyStandardDeep%sSurface omits branches proven false below the preliminary surface.\nfunc applyStandardDeep%sSurface(c *surfaceContext)(int32,bool) {\n", dimension, dimension)
		source.Write(e.body.Bytes())
		if !deepReturns {
			source.WriteString("return 0,false\n")
		}
		source.WriteString("}\n")
	}
	formatted, err := format.Source(source.Bytes())
	must(err)
	must(os.WriteFile(output, formatted, 0644))
}

// must terminates development-time generation on malformed input or IO failure.
func must(err error) {
	if err != nil {
		panic(err)
	}
}

// fields decodes one rule or condition object.
func fields(raw json.RawMessage) map[string]json.RawMessage {
	var value map[string]json.RawMessage
	must(json.Unmarshal(raw, &value))
	return value
}

// stringValue decodes a resource identifier.
func stringValue(raw json.RawMessage) string {
	var value string
	must(json.Unmarshal(raw, &value))
	return value
}

// intValue decodes an integer rule parameter.
func intValue(raw json.RawMessage) int {
	var value int
	must(json.Unmarshal(raw, &value))
	return value
}

// boolValue decodes a boolean rule parameter.
func boolValue(raw json.RawMessage) bool {
	var value bool
	must(json.Unmarshal(raw, &value))
	return value
}

// rule emits first-match ordered surface branches.
func (e *surfaceEmitter) rule(raw json.RawMessage) bool {
	v := fields(raw)
	switch stringValue(v["type"]) {
	case "minecraft:sequence":
		var children []json.RawMessage
		must(json.Unmarshal(v["sequence"], &children))
		for _, child := range children {
			if e.rule(child) {
				return true
			}
		}
	case "minecraft:condition":
		if e.deep && stringValue(fields(v["if_true"])["type"]) == "minecraft:above_preliminary_surface" {
			return false
		}
		fmt.Fprintf(&e.body, "if %s {\n", e.condition(v["if_true"]))
		e.rule(v["then_run"])
		e.body.WriteString("}\n")
	case "minecraft:block":
		index := len(e.states)
		e.states = append(e.states, v["result_state"])
		fmt.Fprintf(&e.body, "return c.system.standardStates[%d],true\n", index)
		return true
	case "minecraft:bandlands":
		e.body.WriteString("return bandSurfaceRule{c.system}.apply(c)\n")
		return true
	default:
		panic("unsupported surface rule")
	}
	return false
}

// condition specializes inexpensive conditions and caches noise predicates through existing slots.
func (e *surfaceEmitter) condition(raw json.RawMessage) string {
	v := fields(raw)
	switch stringValue(v["type"]) {
	case "minecraft:biome":
		var names []string
		must(json.Unmarshal(v["biome_is"], &names))
		terms := make([]string, len(names))
		for index, name := range names {
			id := generatedbiome.BiomeIDByName(name)
			if id < 0 {
				panic(name)
			}
			terms[index] = fmt.Sprintf("c.biomeID()==%d", id)
		}
		return "(" + strings.Join(terms, " || ") + ")"
	case "minecraft:not":
		return "!(" + e.condition(v["invert"]) + ")"
	case "minecraft:above_preliminary_surface":
		return "c.y >= c.minSurfaceLevel"
	case "minecraft:water":
		y := "c.y"
		if boolValue(v["add_stone_depth"]) {
			y += "+c.stoneDepthAbove"
		}
		return fmt.Sprintf("(c.waterHeight==noWaterHeight || %s >= c.waterHeight+(%d)+c.surfaceDepth*(%d))", y, intValue(v["offset"]), intValue(v["surface_depth_multiplier"]))
	case "minecraft:stone_depth":
		depth := "c.stoneDepthAbove"
		if stringValue(v["surface_type"]) == "ceiling" {
			depth = "c.stoneDepthBelow"
		}
		limit := fmt.Sprintf("%d", 1+intValue(v["offset"]))
		if boolValue(v["add_surface_depth"]) {
			limit += "+c.surfaceDepth"
		}
		if size := intValue(v["secondary_depth_range"]); size != 0 {
			limit += fmt.Sprintf("+int(mapRange(c.surfaceSecondary,-1,1,0,%d))", size)
		}
		return depth + " <= " + limit
	case "minecraft:y_above":
		a := surfaceAnchor(v["anchor"])
		y := "c.y"
		if boolValue(v["add_stone_depth"]) {
			y += "+c.stoneDepthAbove"
		}
		return fmt.Sprintf("%s >= %s+c.surfaceDepth*(%d)", y, a, intValue(v["surface_depth_multiplier"]))
	case "minecraft:vertical_gradient":
		index := len(e.gradients)
		e.gradients = append(e.gradients, stringValue(v["random_name"]))
		lower, upper := surfaceAnchor(v["true_at_and_below"]), surfaceAnchor(v["false_at_and_above"])
		return fmt.Sprintf("(c.y <= (%s) || (c.y < (%s) && float64(worldrandom.FirstFloatAt(c.system.standardGradients[%d],int32(c.x),int32(c.y),int32(c.z))) < float64((%s)-c.y)/float64((%s)-(%s))))", lower, upper, index, upper, upper, lower)
	default:
		index := len(e.conditions)
		e.conditions = append(e.conditions, raw)
		return fmt.Sprintf("c.system.standardConditions[%d].test(c)", index)
	}
}

// surfaceAnchor emits a dimension-relative height with its original integer arithmetic.
func surfaceAnchor(raw json.RawMessage) string {
	anchor := fields(raw)
	if value, ok := anchor["absolute"]; ok {
		return fmt.Sprint(intValue(value))
	}
	if value, ok := anchor["above_bottom"]; ok {
		return fmt.Sprintf("c.system.minY+(%d)", intValue(value))
	}
	return fmt.Sprintf("c.system.minY+c.system.height-1-(%d)", intValue(anchor["below_top"]))
}
