//go:build ignore

package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type recipeJSON struct {
	InShape     [][]*int `json:"inShape"`
	Ingredients []int    `json:"ingredients"`
	Result      struct {
		ID    int   `json:"id"`
		Count int32 `json:"count"`
	} `json:"result"`
}

func main() {
	version := flag.String("version", "1.21.4", "Minecraft version")
	flag.Parse()

	projectRoot := findProjectRoot()
	inputFile := filepath.Join(projectRoot, ".mcdata", *version, "recipes.json")
	outputFile := filepath.Join(projectRoot, "internal", "data", "generated", "recipes", "recipes.go")

	data, err := os.ReadFile(inputFile)
	if err != nil {
		fmt.Fprintf(os.Stderr, "read recipes.json: %v\n", err)
		os.Exit(1)
	}

	var rawRecipes map[string][]json.RawMessage
	if err := json.Unmarshal(data, &rawRecipes); err != nil {
		fmt.Fprintf(os.Stderr, "parse recipes.json: %v\n", err)
		os.Exit(1)
	}

	totalRecipes := 0
	for _, recipes := range rawRecipes {
		totalRecipes += len(recipes)
	}

	var itemIDs []string
	for id := range rawRecipes {
		itemIDs = append(itemIDs, id)
	}
	sort.Strings(itemIDs)

	var buf strings.Builder
	buf.WriteString("// Code generated by internal/data/generator/recipes; DO NOT EDIT.\n\n")
	buf.WriteString("package recipes\n\n")
	buf.WriteString("// Recipe is one shaped or shapeless crafting recipe.\n")
	buf.WriteString("type Recipe struct {\n\tPattern [][]int32\n\tIngredients []int32\n\tResult int32\n\tCount int32\n}\n\n")

	buf.WriteString(fmt.Sprintf("const RecipeCount = %d\n", totalRecipes))
	buf.WriteString(fmt.Sprintf("const CraftableItemCount = %d\n\n", len(rawRecipes)))

	buf.WriteString("var CraftableItems = []int{\n")
	for _, id := range itemIDs {
		buf.WriteString(fmt.Sprintf("\t%s,\n", id))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("// CraftingRecipes contains the complete static crafting dataset.\n")
	buf.WriteString("var CraftingRecipes = []Recipe{\n")
	for _, id := range itemIDs {
		for _, raw := range rawRecipes[id] {
			var recipe recipeJSON
			if err := json.Unmarshal(raw, &recipe); err != nil || recipe.Result.ID <= 0 {
				continue
			}
			count := recipe.Result.Count
			if count <= 0 {
				count = 1
			}
			buf.WriteString("\t{")
			if len(recipe.InShape) > 0 {
				buf.WriteString("Pattern: [][]int32{")
				for _, row := range recipe.InShape {
					buf.WriteString("{")
					for _, ingredient := range row {
						if ingredient == nil {
							buf.WriteString("0,")
						} else {
							buf.WriteString(fmt.Sprintf("%d,", *ingredient))
						}
					}
					buf.WriteString("},")
				}
				buf.WriteString("},")
			} else if len(recipe.Ingredients) > 0 {
				buf.WriteString("Ingredients: []int32{")
				for _, ingredient := range recipe.Ingredients {
					buf.WriteString(fmt.Sprintf("%d,", ingredient))
				}
				buf.WriteString("},")
			}
			buf.WriteString(fmt.Sprintf("Result: %d, Count: %d},\n", recipe.Result.ID, count))
		}
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var RecipesPerItem = map[int]int{\n")
	for _, id := range itemIDs {
		buf.WriteString(fmt.Sprintf("\t%s: %d,\n", id, len(rawRecipes[id])))
	}
	buf.WriteString("}\n")

	formatted, err := format.Source([]byte(buf.String()))
	if err != nil {
		fmt.Fprintf(os.Stderr, "format: %v\n", err)
		os.Exit(1)
	}

	if err := os.MkdirAll(filepath.Dir(outputFile), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(outputFile, formatted, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s (%d recipes, %d craftable items)\n", outputFile, totalRecipes, len(rawRecipes))
}

func findProjectRoot() string {
	dir, _ := os.Getwd()
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	wd, _ := os.Getwd()
	return wd
}

func toConstName(name string) string {
	parts := strings.Split(name, "_")
	for i, part := range parts {
		if len(part) > 0 {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return strings.Join(parts, "")
}
