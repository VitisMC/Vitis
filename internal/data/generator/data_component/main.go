//go:build ignore

package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type registriesJSON map[string]registryDef

type registryDef struct {
	ProtocolID int                 `json:"protocol_id"`
	Entries    map[string]entryDef `json:"entries"`
}

type entryDef struct {
	ProtocolID int `json:"protocol_id"`
}

type componentEntry struct {
	Name string
	ID   int
}

func main() {
	version := flag.String("version", "1.21.4", "Minecraft version")
	check := flag.Bool("check", false, "Check component resources without modifying files")
	flag.Parse()
	if *version != "1.21.4" {
		panic("component generator supports protocol 769 only")
	}

	projectRoot := findProjectRoot()
	inputFile := filepath.Join(projectRoot, ".mcdata", *version, "registries.json")
	outputFile := filepath.Join(projectRoot, "internal", "data", "generated", "data_component", "data_components.go")

	data, err := os.ReadFile(inputFile)
	if err != nil {
		fmt.Fprintf(os.Stderr, "read registries.json: %v\n", err)
		os.Exit(1)
	}

	var registries registriesJSON
	if err := json.Unmarshal(data, &registries); err != nil {
		fmt.Fprintf(os.Stderr, "parse registries.json: %v\n", err)
		os.Exit(1)
	}

	registry, ok := registries["minecraft:data_component_type"]
	if !ok {
		fmt.Fprintf(os.Stderr, "minecraft:data_component_type registry not found\n")
		os.Exit(1)
	}

	var components []componentEntry
	for name, entry := range registry.Entries {
		components = append(components, componentEntry{Name: name, ID: entry.ProtocolID})
	}
	sort.Slice(components, func(i, j int) bool {
		return components[i].ID < components[j].ID
	})

	var buf strings.Builder
	buf.WriteString("// Code generated by internal/data/generator/data_component; DO NOT EDIT.\n\n")
	buf.WriteString("package datacomponent\n\n")

	buf.WriteString(fmt.Sprintf("const DataComponentCount = %d\n\n", len(components)))

	buf.WriteString("const (\n")
	for _, c := range components {
		constName := toConstName(strings.TrimPrefix(c.Name, "minecraft:"))
		buf.WriteString(fmt.Sprintf("\tComponent%s int32 = %d\n", constName, c.ID))
	}
	buf.WriteString(")\n\n")

	buf.WriteString("var DataComponentNames = []string{\n")
	for _, c := range components {
		buf.WriteString(fmt.Sprintf("\t%q, // %d\n", c.Name, c.ID))
	}
	buf.WriteString("}\n\n")

	buf.WriteString("var dataComponentByName = map[string]int32{\n")
	for _, c := range components {
		buf.WriteString(fmt.Sprintf("\t%q: %d,\n", c.Name, c.ID))
	}
	buf.WriteString("}\n\n")

	buf.WriteString(`func DataComponentIDByName(name string) int32 {
	if id, ok := dataComponentByName[name]; ok {
		return id
	}
	return -1
}

func DataComponentNameByID(id int32) string {
	if id < 0 || int(id) >= len(DataComponentNames) {
		return ""
	}
	return DataComponentNames[id]
}
`)

	formatted, err := format.Source([]byte(buf.String()))
	if err != nil {
		fmt.Fprintf(os.Stderr, "format: %v\n", err)
		os.Exit(1)
	}

	if err := os.MkdirAll(filepath.Dir(outputFile), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "mkdir: %v\n", err)
		os.Exit(1)
	}

	if *check {
		existing, err := os.ReadFile(outputFile)
		if err != nil || !bytes.Equal(existing, formatted) {
			panic("component registry is stale")
		}
	} else if err := os.WriteFile(outputFile, formatted, 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write: %v\n", err)
		os.Exit(1)
	}

	generateRuntimeResources(projectRoot, *version, *check)
	fmt.Printf("Validated %s (%d data components)\n", outputFile, len(components))
}

func findProjectRoot() string {
	dir, _ := os.Getwd()
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	wd, _ := os.Getwd()
	return wd
}

func toConstName(name string) string {
	parts := strings.Split(name, "_")
	for i, part := range parts {
		if len(part) > 0 {
			parts[i] = strings.ToUpper(part[:1]) + part[1:]
		}
	}
	return strings.Join(parts, "")
}

// generateRuntimeResources derives immutable codecs and defaults from pinned data.
func generateRuntimeResources(root, version string, check bool) {
	data, err := os.ReadFile(filepath.Join(root, ".mcdata", version, "protocol.json"))
	if err != nil {
		panic(err)
	}
	var source struct {
		Types map[string]any `json:"types"`
	}
	if err := json.Unmarshal(data, &source); err != nil {
		panic(err)
	}
	slot, ok := source.Types["SlotComponent"].([]any)
	if !ok || len(slot) != 2 {
		panic("missing component union")
	}
	fields := slot[1].([]any)[1].(map[string]any)["type"].([]any)[1].(map[string]any)["fields"].(map[string]any)
	types := make(map[string]any)
	visited := make(map[string]bool)
	var visit func(any)
	visit = func(value any) {
		switch v := value.(type) {
		case string:
			if visited[v] {
				return
			}
			visited[v] = true
			if definition, ok := source.Types[v]; ok && definition != "native" {
				types[v] = definition
				visit(definition)
			}
		case []any:
			for _, entry := range v {
				visit(entry)
			}
		case map[string]any:
			for key, entry := range v {
				switch key {
				case "type", "fields", "otherwise", "base":
					visit(entry)
				default:
					switch entry.(type) {
					case map[string]any, []any:
						visit(entry)
					}
				}
			}
		}
	}
	for _, definition := range fields {
		visit(definition)
	}
	schema, err := json.Marshal(map[string]any{"components": fields, "types": types})
	if err != nil {
		panic(err)
	}
	items, err := os.ReadFile(filepath.Join(root, ".mcdata", version, "vanilla/reports/items.json"))
	if err != nil {
		panic(err)
	}
	var defaults any
	if err := json.Unmarshal(items, &defaults); err != nil {
		panic(err)
	}
	items, err = json.Marshal(defaults)
	if err != nil {
		panic(err)
	}
	for name, data := range map[string][]byte{"component_schema.json": schema, "item_defaults.json": items} {
		path := filepath.Join(root, "internal/inventory", name)
		if check {
			existing, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(existing, data) {
				panic("stale resource: " + path)
			}
			continue
		}
		if err := os.WriteFile(path, data, 0644); err != nil {
			panic(err)
		}
	}
}
